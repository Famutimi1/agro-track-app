import { Router } from "express";
import { authenticate, authorize } from "../middlewares/auth";
import { getPlatformStats, getLenderAccounts, getTickets, getTicket, replyTicket, getFeatureFlags, toggleFeatureFlag, getAuditLog, getUsers, changeUserRole, setUserStatus, getGrowthAnalytics, getRevenueStats, getSystemHealth, getSettings, updateSettings, updateTicket, setLenderStatus, changeLenderPlan, getDocuments, verifyDocument, getTransactions, getBroadcasts, createBroadcast, sendBroadcast, deleteBroadcast, getTemplates, createTemplate, deleteTemplate, getWebhooks, createWebhook, toggleWebhook, deleteWebhook, getApiKeys, createApiKey, revokeApiKey, getSubscriptions, seedSubscriptions, getInvoices, getInvoice, generateInvoices, recordPayment, voidInvoice } from "../controllers/admin.controller";

export const adminRouter = Router();

adminRouter.use(authenticate, authorize("SUPER_ADMIN"));
adminRouter.get("/stats", getPlatformStats);
adminRouter.get("/lenders", getLenderAccounts);
adminRouter.patch("/lenders/:id/status", setLenderStatus);
adminRouter.patch("/lenders/:id/plan", changeLenderPlan);
adminRouter.get("/tickets", getTickets);
adminRouter.get("/tickets/:id", getTicket);
adminRouter.post("/tickets/:id/reply", replyTicket);
adminRouter.patch("/tickets/:id", updateTicket);
adminRouter.get("/feature-flags", getFeatureFlags);
adminRouter.patch("/feature-flags/:id/toggle", toggleFeatureFlag);
adminRouter.get("/audit-log", getAuditLog);
adminRouter.get("/analytics/growth", getGrowthAnalytics);
adminRouter.get("/analytics/revenue", getRevenueStats);
adminRouter.get("/system-health", getSystemHealth);
adminRouter.get("/settings", getSettings);
adminRouter.patch("/settings", updateSettings);
adminRouter.get("/users", getUsers);
adminRouter.patch("/users/:id/role", changeUserRole);
adminRouter.patch("/users/:id/status", setUserStatus);
adminRouter.get("/documents", getDocuments);
adminRouter.patch("/documents/:id/verify", verifyDocument);
adminRouter.get("/transactions", getTransactions);
adminRouter.get("/broadcasts", getBroadcasts);
adminRouter.post("/broadcasts", createBroadcast);
adminRouter.post("/broadcasts/:id/send", sendBroadcast);
adminRouter.delete("/broadcasts/:id", deleteBroadcast);
adminRouter.get("/templates", getTemplates);
adminRouter.post("/templates", createTemplate);
adminRouter.delete("/templates/:id", deleteTemplate);
adminRouter.get("/webhooks", getWebhooks);
adminRouter.post("/webhooks", createWebhook);
adminRouter.patch("/webhooks/:id/toggle", toggleWebhook);
adminRouter.delete("/webhooks/:id", deleteWebhook);
adminRouter.get("/api-keys", getApiKeys);
adminRouter.post("/api-keys", createApiKey);
adminRouter.delete("/api-keys/:id", revokeApiKey);
adminRouter.get("/billing/subscriptions", getSubscriptions);
adminRouter.post("/billing/subscriptions/seed", seedSubscriptions);
adminRouter.get("/billing/invoices", getInvoices);
adminRouter.post("/billing/invoices/generate", generateInvoices);
adminRouter.get("/billing/invoices/:id", getInvoice);
adminRouter.post("/billing/invoices/:id/payments", recordPayment);
adminRouter.post("/billing/invoices/:id/void", voidInvoice);
